export function getUIText(key: string, locale: SupportedLocale): string {
  const dict = UI_TRANSLATIONS[locale] || UI_TRANSLATIONS['zh-CN'];
  return dict[key] || UI_TRANSLATIONS['zh-CN'][key] || key;
}

export function getEntityName(
  entity: { name: string; displayName?: string; translations?: Record<string, string> | any } | undefined,
  locale: SupportedLocale
): string {
  if (!entity) return '';
  if (entity.translations && entity.translations[locale]) {
    return entity.translations[locale];
  }
  return entity.displayName || entity.name;
}

export function getPokemonTypeLabel(typeKey: string, locale: SupportedLocale): string {
  if (!typeKey) return '';
  const pack = getLanguagePack(locale);
  return pack.terms.pokemon_types?.[typeKey.toLowerCase()] || typeKey;
}

